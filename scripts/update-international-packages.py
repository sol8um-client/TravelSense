def find_package_block(content, title):
    """Return (start, end) char positions of the package block with exact title match."""
    pattern = re.compile(r'  \{\s*\n\s*title:\s*[\'"]' + re.escape(title) + r'[\'"]')
    m = pattern.search(content)
    if not m:
        return None
    start = m.start()
    depth = 0
    i = start
    while i < len(content):
        c = content[i]
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                j = i + 1
                while j < len(content) and content[j] in ',\n':
                    if content[j] == '\n':
                        return (start, j + 1)
                    j += 1
                return (start, j)
        i += 1
    return None


